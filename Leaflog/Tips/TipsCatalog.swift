/// Справочный профиль ухода. Это общие ориентиры для вида, а не диагноз конкретному растению:
/// название растения у пользователя произвольное, поэтому профиль выбирается вручную и необязателен.
struct CareProfile: Identifiable, Hashable {
    let id: String
    let name: String
    let latinName: String
    let light: String
    let watering: String
    let humidity: String
    let temperature: String
    let feeding: String
    let caution: String
    /// Подсказки по сезонам (для сезона, который выбран/определён в приложении).
    let seasonal: [Season: String]

    static func == (l: CareProfile, r: CareProfile) -> Bool { l.id == r.id }
    func hash(into h: inout Hasher) { h.combine(id) }
}

